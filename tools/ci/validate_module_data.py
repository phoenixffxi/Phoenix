"""Validate the module data modules/init.txt enables, the way the server loads it.

Each module file is a JSON merge patch, applied in init.txt order onto the data/ file of the same name, and the
merged result must pass that file's schema in data/schemas (generated by the data_schema_check target). A module
file with no data/ file to patch is never loaded, so it fails too.

Run from the repo root: python -m tools.ci.validate_module_data
"""

import json
import sys
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator

from tools.codegen.common import ROOT
from tools.codegen.validate import (
    MAX_ERRORS,
    YAML_LOADER,
    build_registry,
    node_line,
    validation_message,
    validation_path,
)

MODULES = ROOT / "modules"
DATA = ROOT / "data"
SCHEMAS = DATA / "schemas"


# Mirrors getDataModulePaths in src/map/data/yaml/merge.cpp.
def data_roots() -> list[Path]:
    roots: list[Path] = []
    for line in (MODULES / "init.txt").read_text(encoding="utf-8").splitlines():
        entry = line.strip()
        if not entry or entry.startswith("#"):
            continue

        parts = Path(entry).parts
        root = MODULES / entry if "data" in parts else MODULES / parts[0] / "data"
        if root not in roots and root.is_dir():
            roots.append(root)

    return roots


# RFC 7396, as glz::merge_patch applies it: null deletes, a map merges, anything else replaces.
def merge_patch(target: Any, patch: Any) -> Any:
    if not isinstance(patch, dict):
        return patch

    if not isinstance(target, dict):
        target = {}

    for key, value in patch.items():
        if value is None:
            target.pop(key, None)
        else:
            target[key] = merge_patch(target.get(key), value)

    return target


# How far a patch reaches along an error path, to blame the module line that set it.
def reach(patch: Any, path: list[str | int]) -> int:
    node = patch
    for depth, step in enumerate(path):
        if isinstance(node, dict) and step in node:
            node = node[step]
        elif isinstance(node, list) and isinstance(step, int) and step < len(node):
            node = node[step]
        else:
            return depth

    return len(path)


def main() -> None:
    errors: list[str] = []
    roots = data_roots()
    patches: dict[str, list[Path]] = {}
    for root in roots:
        nested = [
            other for other in roots if other != root and other.is_relative_to(root)
        ]
        for path in sorted(root.rglob("*.yaml")):
            # A deeper init.txt entry owns its own folder.
            if any(path.is_relative_to(other) for other in nested):
                continue

            name = path.relative_to(root).with_suffix("").as_posix()
            if (DATA / f"{name}.yaml").exists():
                patches.setdefault(name, []).append(path)
            # A subfolder data/ does not have is another module's root, one init.txt does not list.
            elif "/" not in name or (DATA / name.split("/")[0]).is_dir():
                errors.append(
                    f"{path.relative_to(ROOT).as_posix()}: no data/{name}.yaml to patch, so the server never loads it"
                )

    if not SCHEMAS.is_dir():
        raise SystemExit(
            "data/schemas is missing: build the data_schema_check target first"
        )

    registry = build_registry(SCHEMAS)
    for name, paths in sorted(patches.items()):
        core = DATA / f"{name}.yaml"
        schema = json.loads(
            (SCHEMAS / f"{core.stem}.schema.json").read_text(encoding="utf-8")
        )
        document = YAML_LOADER.load(core.read_text(encoding="utf-8"))
        loaded = []
        for path in paths:
            patch = YAML_LOADER.load(path.read_text(encoding="utf-8"))
            if patch is None:
                errors.append(
                    f"{path.relative_to(ROOT).as_posix()}: empty, which would replace data/{name}.yaml with nothing"
                )
                continue

            loaded.append((path, patch))
            document = merge_patch(document, patch)

        if not loaded:
            continue

        found = list(
            Draft202012Validator(schema, registry=registry).iter_errors(document)
        )
        print(
            f"validating data/{name}.yaml with {', '.join(p.relative_to(ROOT).as_posix() for p, _ in loaded)} ... {len(found) or 'ok'}"
        )
        for error in found:
            steps = list(error.absolute_path)
            # On a tie the later patch is the one that set the value.
            path, patch = max(reversed(loaded), key=lambda item: reach(item[1], steps))
            line = node_line(patch, steps[: reach(patch, steps)])
            errors.append(
                f"{path.relative_to(ROOT).as_posix()}:{line}: data/{name}.yaml {validation_path(steps)}: {validation_message(error)}"
            )

    if errors:
        print(f"\n{len(errors)} module data errors", file=sys.stderr)
        for error in errors[:MAX_ERRORS]:
            print(error, file=sys.stderr)
        if len(errors) > MAX_ERRORS:
            print(f"... and {len(errors) - MAX_ERRORS} more", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
